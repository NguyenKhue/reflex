/**
 * build.js — `reflex context build`: turn app source into HINTS for the agent that writes
 * screen knowledge. Output goes to `screens/<app>/_app/source/`: `glossary.json` (screen texts,
 * actions, enum labels extracted from Kotlin/Compose) and `source-hints.md` (a readable
 * summary). Nothing here is authoritative — `identify` and the cases are written by hand from
 * what the device actually shows. Only the block between the manual markers is hand-written and
 * it survives every rebuild byte-for-byte.
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { extractKotlin } = require('./extractKotlin');

const MANUAL_START = '<!-- manual:start -->';
const MANUAL_END = '<!-- manual:end -->';
const DEFAULT_MANUAL = [
  '## Source notes (hand-written)',
  '- What the app source says that the device does not: server-driven states, feature flags, deep links.',
  '- Where the real texts come from (a backend payload? the design system?) when they are not literals.',
  '- Which screens this source tree does NOT cover (modules compiled separately, mini apps).',
].join('\n');

function srcCommit(src) {
  try {
    return execFileSync('git', ['-C', src, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim() || null;
  } catch (_) {
    return null;
  }
}

function previousManual(file) {
  if (!fs.existsSync(file)) return null;
  const text = fs.readFileSync(file, 'utf8');
  const start = text.indexOf(MANUAL_START);
  const end = text.indexOf(MANUAL_END);
  if (start < 0 || end < start) return null;
  return text.slice(start + MANUAL_START.length, end);
}

function quoteList(texts, max) {
  const shown = texts.slice(0, max).map((text) => `"${text}"`).join(', ');
  return texts.length > max ? `${shown}, … +${texts.length - max} more` : shown;
}

function renderMarkdown(glossary, manual) {
  const lines = [
    `# Source hints — ${glossary.app}`,
    '',
    `> Generated by \`reflex context build\` from \`${glossary.src}\` @ ${glossary.srcCommit || 'unknown'} on ${glossary.builtAt}.`,
    '> Hints only: `identify` and the cases in `screens/<group>/<screen>/` are written by hand.',
    '> Only the block between the manual markers is hand-written and survives rebuilds.',
    '',
    `${MANUAL_START}${manual === null ? `\n${DEFAULT_MANUAL}\n` : manual}${MANUAL_END}`,
    '',
    `## Screens (${glossary.screens.length})`,
    '',
  ];
  for (const screen of glossary.screens) {
    lines.push(`### ${screen.id} — \`${screen.file}\``);
    if (screen.texts.length) lines.push(`- Texts: ${quoteList(screen.texts, 30)}`);
    const actions = screen.actions.filter((action) => action.to);
    if (actions.length) lines.push(`- Actions: ${actions.map((action) => `${action.label ? `"${action.label}"` : '(action)'} → ${action.to}`).join('; ')}`);
    lines.push('');
  }
  lines.push('## Shared texts', '', glossary.shared.length ? quoteList(glossary.shared, 40) : '(none)', '');
  lines.push('## Launch extras', '', ...(glossary.extras.length ? glossary.extras.map((extra) => `- \`${extra}\``) : ['- none']), '');
  return lines.join('\n');
}

function buildContext({ app, src, root, now = () => new Date() }) {
  if (!/^[a-z0-9][a-z0-9_-]*$/.test(String(app || ''))) throw new Error(`invalid app key "${app || ''}" (expected lowercase a-z0-9_-)`);
  const source = path.resolve(String(src || ''));
  if (!src || !fs.existsSync(source) || !fs.statSync(source).isDirectory()) throw new Error(`--src ${src || ''} is not a directory`);
  if (!root || !fs.existsSync(root)) throw new Error(`workspace root not found: ${root || ''}`);

  const extracted = extractKotlin({ src: source });
  const glossary = {
    app,
    src: source,
    srcCommit: srcCommit(source),
    builtAt: now().toISOString(),
    ...extracted,
  };
  // Inside the app tier, so a screen walk never mistakes the hints for a screen.
  const outDir = path.join(root, 'screens', app, '_app', 'source');
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'glossary.json'), `${JSON.stringify(glossary, null, 2)}\n`);
  const mdFile = path.join(outDir, 'source-hints.md');
  fs.writeFileSync(mdFile, renderMarkdown(glossary, previousManual(mdFile)));
  return { outDir, glossary };
}

module.exports = { buildContext, MANUAL_START, MANUAL_END };
